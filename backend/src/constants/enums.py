from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class RuleStatus(str, Enum):
    candidate = 'candidate'
    replaying = 'replaying'
    ready = 'ready'
    active = 'active'
    retired = 'retired'
class ReplayStatus(str, Enum):
    pending = 'pending'
    running = 'running'
    done = 'done'
    failed = 'failed'
